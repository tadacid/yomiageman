import test from 'node:test';
import assert from 'node:assert/strict';
import {correctSmallKana} from '../web/src/kana-correction.js';
const cases=[
 ['オイラでよければいつしよに行くよ','オイラでよければいっしょに行くよ'],
 ['いつしょにあそぼう','いっしょにあそぼう'],
 ['いっしよに食べよう','いっしょに食べよう'],
 ['ちよつとまってね','ちょっとまってね'],
 ['ちょつとだけ','ちょっとだけ'],
 ['ちよっとだけ','ちょっとだけ'],
 ['ゆつくり休んでね','ゆっくり休んでね'],
 ['びつくりした！','びっくりした！'],
 ['やつぱりまつすぐ行こう','やっぱりまっすぐ行こう'],
 ['そつくりだね','そっくりだね'],
 ['しつかり休んでね','しっかり休んでね'],
 ['すつかり元気だよ','すっかり元気だよ'],
 ['ばつちりだね','ばっちりだね'],
 ['ぐつすり眠ったよ','ぐっすり眠ったよ'],
 ['こつそり出かけるよ','こっそり出かけるよ'],
 ['がつかりしないで','がっかりしないで'],
 ['ぜつたいにできるよ','ぜったいにできるよ'],
 ['さつそく作ろう','さっそく作ろう'],
 ['きのみがいつぱいあるよ','きのみがいっぱいあるよ']
];
for(const [before,after] of cases) test(`限定した表現を補正: ${before}`,()=>assert.equal(correctSmallKana(before),after));
for(const text of [
 'つよいね','いつしようか','いつしようかな？','いつしよ？','いつしょうぶする？',
 'これをもつといいよ','もっとあそぼう','きようだね','きょうはいい日だね',
 'よるにつりをしよう','つぎはよこにおこう','ここにいいものがあるよ',
 'チヨツトという名前','ピカチュウ','10こから11こになった',
 'いっしょにちょっとゆっくり歩こう','しっかりしてね','やっぱりまっすぐ',
 'カイリューとミュウ','いっしょに行くよ\nまたね！'
])test(`正しい・曖昧な表現を変えない: ${text}`,()=>assert.equal(correctSmallKana(text),text));
test('補正を繰り返しても変化しない',()=>{
 for(const [before] of cases){const once=correctSmallKana(before);assert.equal(correctSmallKana(once),once);}
});
